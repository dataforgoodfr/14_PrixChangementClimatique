SELECT
    EXER AS ANNEE,
    IDENT AS SIRET,
    NDEPT AS CODE_DEPARTEMENT,
    INSEE AS CODE_INSEE,
    CREGI AS CODE_REGION,
    TYPE_COMPTE,
    SD AS SOLDE_DEBITEUR,
    SC AS SOLDE_CREDITEUR,
    (SD - SC) AS SOLDE,
    (CAST(NDEPT AS TEXT) || CAST(INSEE AS TEXT)) AS CODE_GEO
FROM 'pipeline_inputs/budget_per_compte_communes.csv'
